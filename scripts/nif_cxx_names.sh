#!/bin/sh
# Writes c_src/cosmo/beam_com_nif_cxx.h: the global names of libc++abi in
# libcosmo.a of cosmocc, for each CPU (beam_com_nif_syms.c, docs/NIFS.md).
# The program gives a C++ NIF object these names, so the process has one
# exception runtime. Run it again after a change of COSMOCC_VERSION:
#
#   sh scripts/nif_cxx_names.sh /path/to/cosmocc > c_src/cosmo/beam_com_nif_cxx.h
#
# The list leaves out the names of beam_com_nif_libc.h, and each name that
# is not a C name (DW.ref.__gxx_personality_v0).
set -eu
C=$1
root=$(cd "$(dirname "$0")/.." && pwd)
tmp=$(mktemp -d "${TMPDIR:-/tmp}/nif_cxx.XXXXXX")
trap 'rm -rf "$tmp"' EXIT
sed -n 's/^NIF_LIBC[A-Z_]*(\(.*\))$/\1/p' "$root/c_src/cosmo/beam_com_nif_libc.h" | sort -u > "$tmp/libc"
cat <<'HEAD'
/*
 * BEAM.com: the names of libc++abi of the program (the members cxa_*,
 * private_typeinfo, stdlib_* of libcosmo.a), which a C++ NIF object can
 * use: exceptions, the personality routine, type info, operator new.
 * Generated by scripts/nif_cxx_names.sh; beam_com_nif_libc.h includes it.
 */
HEAD
for cpu in x86_64 aarch64; do
    lib=$C/$cpu-linux-cosmo/lib/libcosmo.a
    mkdir -p "$tmp/$cpu"
    members=$("$C/bin/$cpu-linux-cosmo-ar" t "$lib" |
        grep -E '^(cxa_[a-z_]+|stdlib_[a-z_]+|private_typeinfo|fallback_malloc|abort_message)\.o$' |
        grep -vE '^cxa(atexit|blocks|finalize|lock|printexits)\.o$' | sort -u)
    (cd "$tmp/$cpu" && "$C/bin/$cpu-linux-cosmo-ar" x "$lib" $members)
    if [ $cpu = x86_64 ]; then echo '#if defined(__x86_64__)'; else echo '#elif defined(__aarch64__)'; fi
    "$C/bin/$cpu-linux-cosmo-nm" --defined-only -g "$tmp/$cpu"/*.o | awk 'NF == 3 { print $3 }' |
        grep -E '^[A-Za-z_][A-Za-z0-9_]*$' | LC_ALL=C sort -u | grep -vxF -f "$tmp/libc" |
        sed 's/.*/NIF_LIBC(&)/'
done
echo '#endif'
