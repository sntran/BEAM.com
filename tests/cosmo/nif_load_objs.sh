#!/bin/sh
# Builds the test objects of tests/cosmo/nif_load_check.c with cosmocc,
# as the NIF objects of a build (`ld -r` of the objects of each CPU), and
# writes OUT/nif_load_objs.h with their bytes. Thus the check carries its
# objects, and runs on each system with no compiler.
#
#   tests/cosmo/nif_load_objs.sh OUT
set -eu
here=$(cd "$(dirname "$0")" && pwd)
out=$1
mkdir -p "$out"
cd "$out"
for f in nif_load_obj_a nif_load_obj_b nif_load_tls nif_load_tls_big; do
    cosmocc -O2 -c "$here/$f.c" -o "$f.o"
done
x86_64-linux-cosmo-ld -r -o obj.x86_64.o nif_load_obj_a.o nif_load_obj_b.o
aarch64-linux-cosmo-ld -r -o obj.aarch64.o .aarch64/nif_load_obj_a.o .aarch64/nif_load_obj_b.o
x86_64-linux-cosmo-ld -r -o objb.x86_64.o nif_load_obj_b.o
aarch64-linux-cosmo-ld -r -o objb.aarch64.o .aarch64/nif_load_obj_b.o
# The TLS models of Rust in assembly: cosmocc takes no .S file, so the
# compiler of each CPU.
x86_64-unknown-cosmo-cc -c "$here/nif_load_tls_asm.S" -o tls_asm.x86_64.o
# The plain gcc keeps "mrs tpidr_el0", as the code of Rust has it.
aarch64-linux-cosmo-gcc -nostdinc -c "$here/nif_load_tls_asm.S" -o tls_asm.aarch64.o
x86_64-linux-cosmo-ld -r -o tls.x86_64.o nif_load_tls.o tls_asm.x86_64.o
aarch64-linux-cosmo-ld -r -o tls.aarch64.o .aarch64/nif_load_tls.o tls_asm.aarch64.o
cosmocc -O2 -ffunction-sections -fdata-sections -c "$here/nif_load_dead.c" -o nif_load_dead.o
x86_64-linux-cosmo-ld -r -o dead.x86_64.r nif_load_dead.o
aarch64-linux-cosmo-ld -r -o dead.aarch64.r .aarch64/nif_load_dead.o
x86_64-unknown-cosmo-objcopy --keep-global-symbol=dead_live dead.x86_64.r dead.x86_64.o
aarch64-unknown-cosmo-objcopy --keep-global-symbol=dead_live dead.aarch64.r dead.aarch64.o
x86_64-linux-cosmo-ld -r -o tlsbig.x86_64.o nif_load_tls_big.o
aarch64-linux-cosmo-ld -r -o tlsbig.aarch64.o .aarch64/nif_load_tls_big.o

emit() {
    printf 'static const unsigned char %s[] __attribute__((aligned(16))) = {\n' "$1"
    od -An -v -tx1 "$2" | sed 's/ *\([0-9a-f][0-9a-f]\)/0x\1,/g'
    printf '};\n'
}
{
    echo "/* Generated by tests/cosmo/nif_load_objs.sh. */"
    emit obj_x86_64 obj.x86_64.o
    emit obj_aarch64 obj.aarch64.o
    emit objb_x86_64 objb.x86_64.o
    emit objb_aarch64 objb.aarch64.o
    emit tls_x86_64 tls.x86_64.o
    emit tls_aarch64 tls.aarch64.o
    emit tlsbig_x86_64 tlsbig.x86_64.o
    emit dead_x86_64 dead.x86_64.o
    emit dead_aarch64 dead.aarch64.o
    emit tlsbig_aarch64 tlsbig.aarch64.o
} > nif_load_objs.h
